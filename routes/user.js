const express =require("express");
const router=express.Router( );
const passport = require("passport");
const wrapasync=require("../util/wrapasync");
const controller=require("../controller/user");
router.get("/",wrapasync(controller.signup));
router.post("/signup",wrapasync(controller.signupForm));
router.get("/login",wrapasync(controller.login));
router.post("/login",passport.authenticate("local",{failureRedirect:"/login",failureFlash:true}),wrapasync(controller.postLogin));
router.get("/logout",controller.logout);
module.exports=router;